async function execute(mode, agent, func, timeout=-1) {
    if (agent.self_prompter.isActive())
        agent.self_prompter.stopLoop();
    if (settings.deterministic_brain && mode.interrupts.includes('all')) {
        const queued = decisionGraph.queueSafetyAction(agent, {
            key: `mode:${mode.name}`,
            goalKey: MODE_SAFETY_GOALS[mode.name] ?? `mode:${mode.name}`,
            priority: MODE_SAFETY_PRIORITIES[mode.name] ?? 50,
            reason: mode.description,
            createAction: () => ({
                name: `mode:${mode.name}`,
                timeout,
                fn: async () => {
                    mode.pending = false;
                    mode.active = true;
                    try { return await func(); }
                    finally { mode.active = false; }
                },
            }),
            onDiscard: () => { mode.pending = false; },
        });
        if (queued) mode.pending = true;
        return;
    }
    let interrupted_action = agent.actions.currentActionLabel;
    mode.active = true;
    let code_return;
    try {
        code_return = await agent.actions.runAction(`mode:${mode.name}`, async () => {
            return await func();
        }, { timeout });
    } finally {
        mode.active = false;
    }
    console.log(`Mode ${mode.name} finished executing, code_return: ${code_return.message}`);

    let should_reprompt = 
        interrupted_action && // it interrupted a previous action
        !settings.deterministic_brain && // deterministic brain retries without another LLM call
        !agent.actions.resume_func && // there is no resume function
        !agent.self_prompter.isActive() && // self prompting is not on
        !code_return.interrupted; // this mode action was not interrupted by something else

    if (should_reprompt) {
        // auto prompt to respond to the interruption
        let role = convoManager.inConversation() ? agent.last_sender : 'system';
        let logs = agent.bot.modes.flushBehaviorLog();
        void agent.enqueueMessage(role, `(AUTO MESSAGE)Your previous action '${interrupted_action}' was interrupted by ${mode.name}.
        Your behavior log: ${logs}\nRespond accordingly.`).catch(error => {
            console.error('Failed to queue mode interruption message:', error);
        });
    }
}

