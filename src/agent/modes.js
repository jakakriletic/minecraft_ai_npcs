// Behavior narration is generated by modes that tick constantly (e.g. self_defense
// fires "Fighting Zombie!" every update while a mob is near), which floods chat. We
// still record every line to behavior_log, but throttle what actually reaches chat:
//   - the same line is not repeated within SAY_DEDUP_MS
//   - at most one behavior line per SAY_MIN_GAP_MS per bot
// This only affects narration; the underlying action (fighting, escaping) still runs.
const SAY_DEDUP_MS = 15000;
const SAY_MIN_GAP_MS = 2500;
const MODE_SAFETY_GOALS = Object.freeze({
    self_preservation: 'escapeHazard',
    emergency_nutrition: 'foodRecovery',
    unstuck: 'stuckRecovery',
    cowardice: 'escapeThreat',
    self_defense: 'combat',
    npc_defense: 'combat',
});
const MODE_SAFETY_PRIORITIES = Object.freeze({
    self_preservation: 100,
    emergency_nutrition: 90,
    cowardice: 80,
    npc_defense: 70,
    self_defense: 60,
    unstuck: 40,
});

export function shouldFleeRecentDamage(bot, hasNearbyThreat = false, now = Date.now()) {
    const recentDangerousDamage = now - Number(bot.lastDamageTime ?? 0) < 3000
        && (Number(bot.health ?? 20) < 10
            || Number(bot.lastDamageTaken ?? 0) >= Number(bot.health ?? 20));
    if (!recentDangerousDamage) return false;

    // Starvation damage has no attacker. Treating it like an ambush made an
    // empty-hunger bot run 20 blocks after every damage tick, permanently
    // pre-empting the deterministic food recovery action.
    return Number(bot.food ?? 20) > 0 || hasNearbyThreat;
}

function say(agent, message) {
    agent.bot.modes.behavior_log += message + '\n';
    if (agent.shut_up || !settings.narrate_behavior) return;
    const now = Date.now();
    const st = agent._sayState || (agent._sayState = { last: 0, recent: new Map() });
    const lastSeen = st.recent.get(message);
    if (lastSeen && now - lastSeen < SAY_DEDUP_MS) return; // exact duplicate, too soon
    if (now - st.last < SAY_MIN_GAP_MS) return;            // global per-bot rate limit
    st.last = now;
    st.recent.set(message, now);
    if (st.recent.size > 40) { // prune stale dedup entries
        for (const [k, t] of st.recent) if (now - t > SAY_DEDUP_MS) st.recent.delete(k);
    }
    void agent.openChat(message).catch(() => {});
}

